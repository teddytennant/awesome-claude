import re,os,sys,subprocess
S,REPO,SRC=sys.argv[1:4]; D=f'{S}/pub/docs'; OUT=f'{REPO}/claudecode/comparison'
rd=lambda f:open(f'{D}/{f}').read()
blob=[]
for r,ds,fs in os.walk(SRC):
    if '.git' in r: continue
    for f in fs:
        if f.endswith(('.ts','.tsx')): blob.append(open(os.path.join(r,f),errors='ignore').read())
src='\n'.join(blob)
def table(path_text,col0=r'^\| `([^`]+)`'):
    return sorted({m.group(1) for m in re.finditer(col0,path_text,re.M)})
def clean(s): return re.sub(r'[\s(\[<].*','',s)
# tools
dt=[n for n in table(rd('tools-reference.md').split('## ')[1] if False else rd('tools-reference.md')) if re.fullmatch(r'[A-Z][A-Za-z]+',n)]
sn_t=set(re.findall(r"(?:_TOOL_NAME|TOOL_NAME)\s*=\s*'([A-Z][A-Za-z]+)'",src))
sn_t|=set(re.findall(r"name(?:: |\s*=\s*)'([A-Z][A-Za-z]+)'",'\n'.join(open(os.path.join(r,f),errors='ignore').read() for r,_,fs in os.walk(f'{SRC}/tools') for f in fs if f.endswith(('.ts','.tsx')))))
sn_t|={'ListMcpResourcesTool','ReadMcpResourceTool'}
sn_t={x for x in sn_t if not x.endswith('Error')}
# commands
dc=sorted({clean(n).lstrip('/') for n in table(rd('commands.md'),r'^\| `/([^`]+)`')})
sn_c=set(re.findall(r"name:\s*'([a-z][a-z0-9-]+)'",'\n'.join(open(os.path.join(r,f),errors='ignore').read() for r,_,fs in os.walk(f'{SRC}/commands') for f in fs if f.endswith(('.ts','.tsx')))))
sn_c|={d.replace('.tsx','').replace('.ts','') for d in os.listdir(f'{SRC}/commands')}
cmdsrc='\n'.join(open(os.path.join(r,f),errors='ignore').read() for r,_,fs in os.walk(f'{SRC}/commands') for f in fs if f.endswith(('.ts','.tsx')))
for a in re.findall(r"aliases:[^\[\n]*\[([^\]]*)\]",cmdsrc): sn_c|=set(re.findall(r"'([\w-]+)'",a))
HV=set('PreToolUse PostToolUse Stop Notification Setup Elicitation SessionStart'.split())
sn_c|=set(re.findall(r"name:\s*'([a-z][a-z0-9-]+)'",'\n'.join(open(f'{SRC}/skills/bundled/'+f,errors='ignore').read() for f in os.listdir(f'{SRC}/skills/bundled'))))
# env
de=sorted(set(re.findall(r'`([A-Z][A-Z0-9_]{3,})`',rd('env-vars.md'))))
sn_e=set(re.findall(r'process\.env\.([A-Z][A-Z0-9_]+)',src))|set(re.findall(r"['\"]([A-Z][A-Z0-9]*_[A-Z0-9_]+)['\"]",src))
# hooks
dh=sorted(set(x[0] for x in re.findall(r'^#{2,4} ([A-Z][a-z]+(?:[A-Z][a-z]+)*)( input| decision control)?\s*$',rd('hooks.md'),re.M)))
m=re.search(r'export const HOOK_EVENTS\s*=\s*\[(.*?)\]',open(f'{SRC}/entrypoints/sdk/coreTypes.ts').read(),re.S); sn_h=set(re.findall(r"'(\w+)'",m.group(1)))
# flags
help=open(f'{S}/pub/help.txt').read()+rd('cli-reference.md')
df=sorted(set(re.findall(r'(?<![\w-])--[a-z][a-z0-9-]+',help)))
sn_f=set(re.findall(r'--[a-z][a-z0-9-]+',open(f'{SRC}/main.tsx',errors='ignore').read()))
# settings
ds=sorted(set(re.findall(r'^\| \[`([A-Za-z][\w.]*)`\]',rd('settings-reference.md'),re.M)))
sf=open(f'{SRC}/utils/settings/types.ts',errors='ignore').read()
sn_s=set(re.findall(r'^\s*([a-zA-Z]\w+):\s',sf,re.M))
def inv(name,doc,snap,file,fmt='`{}`',showold=True,note=''):
    doc=set(doc); both=sorted(doc&snap); new=sorted(doc-snap); old=sorted(snap-doc)
    o=[f'# {name}: snapshot vs. current docs\n',f'Documented now: **{len(doc)}**. In the snapshot: **{len(snap)}**. In both: **{len(both)}**. New since the snapshot: **{len(new)}**. In the snapshot only: **{len(old)}**.\n',note,'\nGenerated by name match, so a renamed item appears on both sides, and a snapshot-only name may be internal, gated, undocumented or removed.\n',f'## New since the snapshot ({len(new)})\n']+['- '+fmt.format(x) for x in new]
    if showold: o+=[f'\n## In the snapshot, not in current docs ({len(old)})\n']+['- '+fmt.format(x) for x in old]
    o+=[f'\n## In both ({len(both)})\n',', '.join(fmt.format(x) for x in both)]
    open(f'{OUT}/{file}','w').write('\n'.join(o)+'\n'); return name,len(doc),len(snap),len(both),len(new),len(old),file
dh=[x for x in dh if x in sn_h or re.search('`'+x+'`',rd('hooks.md'))]
R=[inv('Tools',dt,sn_t,'tools.md'),inv('Slash commands',dc,sn_c,'commands.md','`/{}`'),inv('Hook events',dh,sn_h,'hook-events.md'),inv('CLI flags',df,sn_f,'cli-flags.md'),inv('Settings keys',ds,sn_s,'settings.md',note='Top-level and dotted keys from the settings reference; dotted keys never match the snapshot schema by name, so treat those as unverified.',showold=False),inv('Environment variables',de,sn_e,'env-vars.md',showold=False,note='Snapshot-only names are counted but not listed, since most are internal.')]
o=['# Snapshot vs. current release\n','Name-level inventory of the 2026-03-31 snapshot against the public docs for 2.1.314.\n','| Surface | Documented now | Snapshot | Both | New | Snapshot only |','|---|---|---|---|---|---|']
for r in R: o.append(f'| [{r[0]}]({r[6]}) | {r[1]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} |')
open(f'{OUT}/README.md','w').write('\n'.join(o)+'\n')
for r in R: print(r)
print('tools new',sorted(set(dt)-sn_t)); print('hooks new',sorted(set(dh)-sn_h)); print('cmds new',sorted(set(dc)-sn_c)); print('tools old',sorted(sn_t-set(dt)))
print('hook snap', sorted(sn_h)[:40])
