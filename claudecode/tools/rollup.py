import os,re,sys
R,S=sys.argv[1:3]; C=f'{R}/claudecode'; SP=f'{C}/specs'
names={'core':'Core runtime','tools':'Built-in tools','agents':'Agents and orchestration','extensibility':'Extensibility','security':'Permissions and security','memory-context':'Memory, context and settings','interface':'Terminal interface and CLI','platforms':'Platforms and integrations'}
idx=['# Spec index\n'];oq=['# Open questions\n','Everything the specs could not establish, collected from each spec\'s Open questions section. Regenerated by `tools/rollup.py`.\n'];cnt={}
for a,n in names.items():
    idx.append(f'\n## {n}\n\n| Spec | Status | Provenance |\n|---|---|---|'); oq.append(f'\n## {n}\n')
    for f in sorted(os.listdir(f'{SP}/{a}')):
        t=open(f'{SP}/{a}/{f}').read()
        ti=re.search(r'^# (.+)',t,re.M).group(1)
        g=lambda k:(re.search(rf'\*\*{k}:\*\*\s*(.+)',t) or [0,'?'])[1].strip()
        st=g('Status').split('.')[0][:60];pv=g('Provenance').split('.')[0][:70]
        idx.append(f'| [{ti}](specs/{a}/{f}) | {st.replace("|","/")} | {pv.replace("|","/")} |')
        k=re.search(r'^## Open questions\s*\n(.*?)(?=^## |\Z)',t,re.M|re.S)
        if k and k[1].strip():
            oq.append(f'\n### [{ti}](specs/{a}/{f})\n\n'+re.sub(r'\]\((?!http|#)(?:\./)?([^)]+\.md)',lambda x:f'](specs/{a}/{x[1]})',k[1].strip()))
            cnt[a]=cnt.get(a,0)+len(re.findall(r'^\s*(?:[-*]|\d+\.) ',k[1],re.M))
open(f'{C}/INDEX.md','w').write('\n'.join(idx)+'\n'); open(f'{C}/OPEN-QUESTIONS.md','w').write('\n'.join(oq)+'\n')
w=open(f'{S}/pub/docs/whats-new__index.md').read()
o=['# Features since the snapshot\n','The headline features of each week, taken from the public weekly digests. The digests stop at 2026 week 37, so the later months come from the changelog\'s "Added" entries. The complete record is in [releases/](releases/README.md).\n']
for m in re.finditer(r'\*\*Week (\d+)\*\*\s*\n+(.+?)\n+(.*?)(?=\[Read the Week|\Z)',w,re.S):
    b=re.sub(r'\s+',' ',m[3]).strip(); o.append(f'## Week {m[1]} ({m[2].strip()})\n\n{b}\n')
wk=len(o)-2
o.append('## After the digests: Sep 12 to Oct 30\n')
for f in ['2026-09.md','2026-10.md']:
    for l in open(f'{C}/releases/{f}'):
        if l.startswith('## '):
            v=l[3:].split(' (')[0]; p=0
            dt=v.split(' — ')[1]
        elif re.match(r'- `[\w-]+` Added ',l) and dt>='2026-09-12':
            o.append(f'- {v.split(" — ")[0]}: '+re.sub(r'^- `[\w-]+` Added ','',l).strip())
open(f'{C}/FEATURES-SINCE-SNAPSHOT.md','w').write('\n'.join(o)+'\n')
print(wk,cnt,sum(cnt.values()),len(o))
